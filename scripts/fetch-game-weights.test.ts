// @vitest-environment node
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { fetchWeights, readGames, readPrevious, renderMap, run } from './fetch-game-weights.ts';

type Fetch = typeof fetch;

const GAMES = `export const GAMES: Game[] = [
  {
    name: 'Catan',
    slug: 'catan',
    players: '3-4',
    bgg: 13,
    subgames: [
      {
        name: "Catan: Seafarers",
        slug: 'seafarers',
        kind: 'expansion',
        bgg: 325,
      },
    ],
  },
  {
    name: 'Card Deck',
    slug: 'card-deck',
    subgames: [
      {
        name: 'Spades',
        slug: 'spades',
        bgg: 592,
      },
    ],
  },
];
`;

const WISHLIST = `const ENTRIES: WishlistItem[] = [
  {
    id: 'lost-cities',
    bgg: 50,
    name: 'Lost Cities',
  },
  {
    id: 'catan',
    bgg: 13,
    name: 'Catan',
  },
];
`;

const STATS = (bgg: number) => `https://api.geekdo.com/api/dynamicinfo?objectid=${bgg}&objecttype=thing`;
const stats = (avgweight: string, numweights: string) =>
  new Response(JSON.stringify({ item: { stats: { avgweight, numweights } } }));

/** A fetch answering each URL from `answers`, failing a test that asks for any other. */
function fakeFetch(answers: Record<string, () => Response | Promise<Response>>) {
  return vi.fn<Fetch>((input) => {
    const answer = answers[String(input)];
    if (!answer) throw new Error(`unexpected fetch of ${String(input)}`);
    return Promise.resolve(answer());
  });
}

const pause = () => Promise.resolve();

beforeEach(() => {
  vi.spyOn(console, 'log').mockImplementation(() => {});
  vi.spyOn(console, 'warn').mockImplementation(() => {});
  vi.spyOn(console, 'error').mockImplementation(() => {});
});
afterEach(() => vi.restoreAllMocks());

describe('readGames', () => {
  it("reads every game and game inside one with an id, and the wishlist's, each id once", () => {
    expect(readGames(GAMES, WISHLIST)).toEqual([
      { name: 'Catan', bgg: 13 },
      { name: 'Catan: Seafarers', bgg: 325 },
      { name: 'Spades', bgg: 592 },
      { name: 'Lost Cities', bgg: 50 },
    ]);
  });

  it("never gives a game without an id the id of the next game's", () => {
    expect(readGames(GAMES, WISHLIST).map((g) => g.name)).not.toContain('Card Deck');
  });

  it('reads every id in games.ts and wishlist.ts as they stand', () => {
    const games = readFileSync('src/data/games.ts', 'utf8');
    const wishlist = readFileSync('src/data/wishlist.ts', 'utf8');
    const ids = new Set([...`${games}${wishlist}`.matchAll(/\bbgg: (\d+),/g)].map((m) => Number(m[1])));
    const found = readGames(games, wishlist);
    expect(new Set(found.map((g) => g.bgg))).toEqual(ids);
    expect(found).toContainEqual({ name: 'One Night Werewolf', bgg: 147949 });
  });

  it('refuses sources it finds no ids in', () => {
    expect(() => readGames('export const GAMES = [];', WISHLIST)).toThrow(
      'no BoardGameGeek ids found in src/data/games.ts',
    );
    expect(() => readGames(GAMES, 'const ENTRIES = [];')).toThrow('no BoardGameGeek ids found in src/data/wishlist.ts');
  });
});

describe('readPrevious', () => {
  it('reads back the weights and nulls a map it wrote', () => {
    const games = [
      { name: 'Catan', bgg: 13 },
      { name: 'Spades', bgg: 592 },
    ];
    const weights = new Map([
      [592, null],
      [13, 2.28],
    ]);
    expect(readPrevious(renderMap(games, weights))).toEqual(weights);
  });
});

describe('renderMap', () => {
  it('lists the weights by id, in order, each named', () => {
    const source = renderMap(
      [
        { name: 'Spades', bgg: 592 },
        { name: 'Catan', bgg: 13 },
      ],
      new Map([
        [592, null],
        [13, 2.28],
      ]),
    );
    expect(source).toContain(
      'export const GAME_WEIGHTS: Record<number, number | null> = {\n  13: 2.28, // Catan\n  592: null, // Spades\n};\n',
    );
    expect(source).toMatch(/^\/\/ Generated by `npm run game-weights`/);
  });
});

describe('fetchWeights', () => {
  const games = [
    { name: 'Catan', bgg: 13 },
    { name: 'Lost Cities', bgg: 50 },
    { name: 'Spades', bgg: 592 },
  ];

  it('rounds a voted weight to two places, and pauses after each game', async () => {
    const fetch = fakeFetch({
      [STATS(13)]: () => stats('2.2837', '1500'),
      [STATS(50)]: () => stats('1.4712', '800'),
      [STATS(592)]: () => stats('2.031', '90'),
    });
    const wait = vi.fn(pause);
    const weights = await fetchWeights(games, new Map(), { fetch, pause: wait });
    expect(weights).toEqual(
      new Map([
        [13, 2.28],
        [50, 1.47],
        [592, 2.03],
      ]),
    );
    expect(wait).toHaveBeenCalledTimes(3);
  });

  it('keeps null for a game with no votes or a weight out of range', async () => {
    const fetch = fakeFetch({
      [STATS(13)]: () => stats('0', '0'),
      [STATS(50)]: () => stats('7', '3'),
      [STATS(592)]: () => new Response(JSON.stringify({ item: { stats: {} } })),
    });
    const weights = await fetchWeights(games, new Map([[13, 2.28]]), { fetch, pause });
    expect(weights).toEqual(
      new Map([
        [13, null],
        [50, null],
        [592, null],
      ]),
    );
  });

  it('keeps the last weight for a game BGG gives no answer for, and goes on', async () => {
    const fetch = fakeFetch({
      [STATS(13)]: () => new Response('oops', { status: 500 }),
      [STATS(50)]: () => new Response('<html>not json</html>'),
      [STATS(592)]: () => stats('2', '10'),
    });
    const weights = await fetchWeights(games, new Map([[13, 2.28]]), { fetch, pause });
    // Lost Cities had no weight before, so it stays out of the map.
    expect(weights).toEqual(
      new Map([
        [13, 2.28],
        [592, 2],
      ]),
    );
    expect(console.warn).toHaveBeenCalledWith('no answer for Catan (BGG 13, 500); keeping its last weight');
  });

  it('stops at a rate limit, keeping the last weights for the rest', async () => {
    const fetch = fakeFetch({
      [STATS(13)]: () => stats('3', '10'),
      [STATS(50)]: () => new Response('', { status: 429 }),
    });
    const previous = new Map<number, number | null>([
      [13, 2],
      [50, 1.5],
      [592, null],
    ]);
    const weights = await fetchWeights(games, previous, { fetch, pause });
    expect(weights).toEqual(
      new Map([
        [13, 3],
        [50, 1.5],
        [592, null],
      ]),
    );
    expect(fetch).toHaveBeenCalledTimes(2);
    expect(console.error).toHaveBeenCalledWith(
      'BoardGameGeek is rate limiting (429) at Lost Cities; keeping the last weights for the rest, re-run later.',
    );
  });

  it('stops when BGG stalls, as at a rate limit', async () => {
    const fetch = vi.fn<Fetch>(() => Promise.reject(new DOMException('timed out', 'TimeoutError')));
    const weights = await fetchWeights(games, new Map([[50, 1.5]]), { fetch, pause });
    expect(weights).toEqual(new Map([[50, 1.5]]));
    expect(fetch).toHaveBeenCalledTimes(1);
    expect(console.error).toHaveBeenCalledWith(
      'BoardGameGeek stopped answering at Catan; keeping the last weights for the rest, re-run later.',
    );
  });

  it('fails on any other network error', async () => {
    const fetch = vi.fn<Fetch>(() => Promise.reject(new TypeError('fetch failed')));
    await expect(fetchWeights(games, new Map(), { fetch, pause })).rejects.toThrow('fetch failed');
  });
});

describe('run', () => {
  let dir: string;
  beforeEach(() => {
    dir = mkdtempSync(join(tmpdir(), 'game-weights-'));
    mkdirSync(join(dir, 'src/data'), { recursive: true });
    writeFileSync(join(dir, 'src/data/games.ts'), GAMES);
    writeFileSync(join(dir, 'src/data/wishlist.ts'), WISHLIST);
  });
  afterEach(() => rmSync(dir, { recursive: true, force: true }));

  const map = () => readFileSync(join(dir, 'src/data/gameWeights.ts'), 'utf8');

  it('writes the map from scratch', async () => {
    const fetch = fakeFetch({
      [STATS(13)]: () => stats('2.28', '10'),
      [STATS(325)]: () => stats('0', '0'),
      [STATS(592)]: () => stats('2.03', '10'),
      [STATS(50)]: () => stats('1.47', '10'),
    });
    await run({ dir, fetch, pause });
    expect(readPrevious(map())).toEqual(
      new Map([
        [13, 2.28],
        [50, 1.47],
        [325, null],
        [592, 2.03],
      ]),
    );
    expect(console.log).toHaveBeenLastCalledWith('3 of 4 games have a weight.');
  });

  it('keeps what the last map had for the games a cut-short run does not reach, and drops ids no longer listed', async () => {
    writeFileSync(
      join(dir, 'src/data/gameWeights.ts'),
      renderMap(
        [],
        new Map([
          [13, 2.1],
          [50, 1.4],
          [325, 2.4],
          [999, 3],
        ]),
      ),
    );
    const fetch = fakeFetch({
      [STATS(13)]: () => stats('2.28', '10'),
      [STATS(325)]: () => new Response('', { status: 429 }),
    });
    await run({ dir, fetch, pause });
    expect(readPrevious(map())).toEqual(
      new Map([
        [13, 2.28],
        [50, 1.4],
        [325, 2.4],
      ]),
    );
    expect(map()).toContain('  50: 1.4, // Lost Cities\n');
  });
});
